@Composable
fun ManagementAgentsScreen(repository: AgentManagementRepository, configurationScope: ConfigurationScope,
    onScopeChange: (ConfigurationScope) -> Unit, onBack: () -> Unit, registerBack: ((() -> Boolean)?) -> Unit,
    initialAgent: String? = null) {
    val state by repository.state.collectAsState()
    val layer = if (configurationScope == ConfigurationScope.GLOBAL) state.globalValues else state.projectValues
    val disabledInScope = configurationStrings(configurationValue(layer, "task.disabledAgents"))
    val actions = LocalManagementActions.current
    var route by remember { mutableStateOf("list") }
    var selected by remember { mutableStateOf<ManagedAgent?>(null) }
    var generated by remember { mutableStateOf<ManagedAgent?>(null) }
    var query by rememberSaveable { mutableStateOf("") }
    var filter by rememberSaveable { mutableStateOf("all") }
    var create by remember { mutableStateOf(false) }
    var deleting by remember { mutableStateOf(false) }
    val agent = state.agents.firstOrNull { it.name == selected?.name } ?: selected
    var initialPending by rememberSaveable(initialAgent) { mutableStateOf(initialAgent != null) }
    LaunchedEffect(initialAgent, state.loading, state.agents) {
        if (initialPending && !state.loading) {
            initialPending = false
            selected = state.agents.firstOrNull { it.name == initialAgent }
            if (selected != null) route = "detail"
            else {
                query = initialAgent.orEmpty()
                actions.launch { error("当前容器未发现 Agent 定义：${initialAgent.orEmpty()}") }
            }
        }
    }
    val back = { route = if (route == "detail" || route == "generate" || selected == null) "list" else "detail" }
    val pageStates = rememberSaveableStateHolder()
    pageStates.SaveableStateProvider(if (route == "list") "list" else "$route:${selected?.path.orEmpty()}") {
        if (route == "edit" || route == "raw") {
            AgentDefinitionEditor(repository, state, selected, generated, configurationScope, onScopeChange,
                { generated = null; back() }, registerBack, rawInitially = route == "raw")
        } else if (route == "overrides" && agent != null) {
            AgentOverrides(repository, state, agent, configurationScope, onScopeChange, back, registerBack)
        } else if (route == "generate") {
            AgentGeneration(repository, state, configurationScope, onScopeChange, back, registerBack,
                { generated = it; selected = null; route = "edit" })
        } else {
            AgentManagementBack(registerBack) {
                when { deleting -> { deleting = false; true }; create -> { create = false; true }
                    route != "list" -> { back(); true }; else -> false }
            }
            if (route == "detail" && agent != null) {
                val disabled = configurationStrings(configurationValue(state.effectiveValues, "task.disabledAgents"))
                var more by remember { mutableStateOf(false) }
                fun toggle(enabled: Boolean) = actions.launch { repository.updateSettings(configurationScope,
                    mapOf("task.disabledAgents" to if (enabled) disabledInScope - agent.name else (disabledInScope + agent.name).distinct())) }
                fun copy(scope: ConfigurationScope) = actions.launch("已复制定义") {
                    repository.saveAgent(scope, agent.name, agent.fields, agent.systemPrompt)
                }
                ManagementPage(agent.name, back, actions = { Box {
                    AgentIconButton("more_vert", "更多", { more = true })
                    ManagementMenu(more, { more = false }) {
                        ManagementMenuItem(text = { Text("复制到项目") }, leadingIcon = { Symbol("folder") }, enabled = state.context.projectPath != null, onClick = { more = false; copy(ConfigurationScope.PROJECT) })
                        ManagementMenuItem(text = { Text("复制到用户") }, leadingIcon = { Symbol("person") }, onClick = { more = false; copy(ConfigurationScope.GLOBAL) })
                        ManagementMenuItem(text = { Text("查看原始定义") }, leadingIcon = { Symbol("data_object") }, onClick = { more = false; selected = agent; route = "raw" })
                    }
                } }) {
                    Row(Modifier.fillMaxWidth().padding(4.dp, 4.dp, 4.dp, 16.dp), verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(16.dp)) {
                        Box(Modifier.size(64.dp).background(LocalAgentColors.current.primaryContainer, RoundedCornerShape(14.dp)), contentAlignment = Alignment.Center) { Symbol("smart_toy", size = 32.dp, tint = LocalAgentColors.current.onPrimaryContainer) }
                        Column { Text(agent.name, style = MaterialTheme.typography.headlineSmall); Text(agent.description, color = LocalAgentColors.current.onSurfaceVariant) }
                    }
                    Column {
                        ManagementRow("启用", "停用按名称生效", icon = "power_settings_new", trailing = {
                            Switch(agent.name !in disabled, { toggle(it) }, enabled = !actions.busy)
                        })
                    }
                    ManagementGroup("来源") {
                        ManagementLayers(listOf(ManagementLayer("生效定义 · ${managementSourceLabel(agent.source)}", agent.path, selected = true)) +
                            agent.shadows.map { ManagementLayer("被遮蔽 · ${managementSourceLabel(it.source)}", it.path) })
                        if (agent.shadows.isNotEmpty()) ManagementHint("同名定义整份覆盖，不逐字段合并", "layers")
                        if (agent.readOnly) ManagementBanner("只读来源；复制后编辑不会修改安装包。副本会遮蔽当前定义。", "lock")
                        if (agent.readOnly) {
                        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            TextButton(onClick = { copy(ConfigurationScope.PROJECT) }, enabled = state.context.projectPath != null && !actions.busy) { Text("复制到项目") }
                            TextButton(onClick = { copy(ConfigurationScope.GLOBAL) }, enabled = !actions.busy) { Text("复制到用户") }
                        }
                        }
                    }
                    ManagementGroup("配置") {
                        ManagementRow(if (agent.readOnly) "查看定义" else "编辑定义", "提示词、模型、工具和输出", "edit_note",
                            { selected = agent; generated = null; route = "edit" }, index = 0, count = 2)
                        val overrideCount = listOf("task.agentModelOverrides", "task.agentPrewalk", "task.agentAdvisor", "task.agentSoftRequestBudget", "task.agentServiceTierOverrides", "task.agentCompactionThresholdOverrides", "task.agentAccountPools").count { configurationMap(configurationValue(state.effectiveValues, it)).containsKey(agent.name) }
                        ManagementRow("运行覆盖", if (overrideCount == 0) "沿用定义" else "$overrideCount 项覆盖", "tune", { route = "overrides" }, index = 1, count = 2)
                    }
                    ManagementGroup("当前模型") {
                        val models = configurationStrings(configurationMap(configurationValue(state.effectiveValues, "task.agentModelOverrides"))[agent.name] ?: agent.fields["model"])
                        ManagementCandidates(models, state, {}, readOnly = true)
                        if (models.isEmpty()) ManagementHint("未设置，跟随子任务角色", "link")
                    }
                    if (!agent.readOnly) TextButton(onClick = { deleting = true }) { Text("删除定义", color = MaterialTheme.colorScheme.error) }
                }
                if (deleting) AlertDialog(onDismissRequest = { deleting = false }, title = { Text("删除定义？") },
                    text = { Text("将删除 ${agent.path}。\n" + (agent.shadows.firstOrNull()?.let {
                        "下层 ${managementSourceLabel(it.source)} 定义将重新生效：${it.path}"
                    } ?: "没有同名下层定义，Agent 将消失。") + "\n按名称保存的运行覆盖不会被删除。") },
                    confirmButton = { TextButton(onClick = { actions.launch { repository.deleteAgent(agent); deleting = false; route = "list" } }) { Text("删除") } },
                    dismissButton = { TextButton(onClick = { deleting = false }) { Text("取消") } })
            } else ManagementPage("Agent 管理", onBack,
                actions = { ManagementScopeChip(configurationScope, onScopeChange, state.context.projectPath != null) },
                fab = { Box {
                    ManagementFab("新建", onClick = { create = true })
                    ManagementMenu(create, { create = false }) {
                        ManagementMenuItem(text = { Text("描述需求，AI 生成") }, leadingIcon = { Symbol("auto_awesome") }, onClick = { create = false; selected = null; generated = null; route = "generate" })
                        ManagementMenuItem(text = { Text("手工新建") }, leadingIcon = { Symbol("edit_note") }, onClick = { create = false; selected = null; generated = null; route = "edit" })
                    }
                } }) {
                SettingsSearch(query, { query = it }, "搜索 Agent")
                val disabled = configurationStrings(configurationValue(state.effectiveValues, "task.disabledAgents"))
                AgentChoiceChips(listOf("all" to "全部") + state.agents.map { it.source }.distinct().map { it to managementSourceLabel(it) } + ("disabled" to "已停用"), filter, { filter = it })
                val agents = state.agents.filter { (filter == "all" || it.source == filter || (filter == "disabled" && it.name in disabled)) &&
                    (it.name.contains(query, true) || it.description.contains(query, true)) }
                Column(Modifier.padding(top = 12.dp), verticalArrangement = Arrangement.spacedBy(3.dp)) {
                    agents.forEachIndexed { index, item ->
                        ManagementRow(item.name, item.description,
                            when (item.source) { "project" -> "folder"; "user" -> "person"; "bundled" -> "inventory_2"; else -> "extension" },
                            { selected = item; route = "detail" }, index = index, count = agents.size,
                            detail = configurationStrings(configurationMap(configurationValue(state.effectiveValues, "task.agentModelOverrides"))[item.name] ?: item.fields["model"]).joinToString("，").ifEmpty { "默认模型" },
                            trailing = {
                                Switch(item.name !in disabled, { enabled -> actions.launch {
                                    repository.updateSettings(configurationScope, mapOf("task.disabledAgents" to
                                        if (enabled) disabledInScope - item.name else (disabledInScope + item.name).distinct()))
                                } }, enabled = !actions.busy)
                            })
                    }
                    if (agents.isEmpty()) ManagementHint(if (query.isBlank()) "此来源没有 Agent；可新建自定义定义。" else "没有匹配的 Agent", "search_off")
                }
            }
        }
    }
}

@Composable
internal fun AgentManagementBack(registerBack: ((() -> Boolean)?) -> Unit, back: () -> Boolean) {
    val current by rememberUpdatedState(back)
    DisposableEffect(registerBack) { registerBack { current() }; onDispose { registerBack(null) } }
}

@OptIn(ExperimentalLayoutApi::class)
@Composable
internal fun AgentChoiceChips(options: List<Pair<String, String>>, selected: String, onSelect: (String) -> Unit, enabled: Boolean = true) {
    FlowRow(horizontalArrangement = Arrangement.spacedBy(8.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
        options.forEach { (value, label) -> ManagementChip(label, value == selected, { onSelect(value) }, enabled) }
    }
}

@OptIn(ExperimentalLayoutApi::class)
@Composable
internal fun AgentCatalogueSelection(title: String, available: List<ConfigurationCapability>, selected: List<String>,
    enabled: Boolean = true, onChange: (List<String>) -> Unit) {
    ManagementGroup(title) {
        FlowRow(horizontalArrangement = Arrangement.spacedBy(8.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
            (available.map { it.name } + selected).distinct().forEach { name ->
                ManagementChip(name + if (available.none { it.name == name }) " · 未发现" else "", name in selected,
                    { onChange(if (name in selected) selected - name else selected + name) }, enabled)
            }
        }
    }
}

@Composable
private fun AgentDefinitionEditor(repository: AgentManagementRepository, state: AgentManagementState, original: ManagedAgent?,
    initial: ManagedAgent?, defaultScope: ConfigurationScope, onScopeChange: (ConfigurationScope) -> Unit,
    onBack: () -> Unit, registerBack: ((() -> Boolean)?) -> Unit, rawInitially: Boolean = false) {
    val actions = LocalManagementActions.current
    val base = original ?: initial
    val readOnly = original?.readOnly == true
    var name by remember { mutableStateOf(base?.name.orEmpty()) }
    var fields by remember { mutableStateOf(base?.fields.orEmpty()) }
    var prompt by remember { mutableStateOf(base?.systemPrompt.orEmpty()) }
    var scope by remember { mutableStateOf(original?.let { if (it.source == "project") ConfigurationScope.PROJECT else ConfigurationScope.GLOBAL } ?: defaultScope) }
    var baseline by remember { mutableStateOf(Triple(name, fields, prompt)) }
    var baselineScope by remember { mutableStateOf(scope) }
    var raw by remember { mutableStateOf(rawInitially) }
    var rawText by remember { mutableStateOf(base?.content.orEmpty()) }
    var rawBaseline by remember { mutableStateOf(base?.content.orEmpty()) }
    var full by remember { mutableStateOf<String?>(null) }
    var preview by remember { mutableStateOf(false) }
    var discard by remember { mutableStateOf(false) }
    var thinking by remember { mutableStateOf(false) }
    var target by remember { mutableStateOf<String?>(null) }
    var editorBack by remember { mutableStateOf<(() -> Unit)?>(null) }
    var choosingSpawns by remember { mutableStateOf(false) }
    val dirty = name != baseline.first || fields != baseline.second || prompt != baseline.third || scope != baselineScope || (raw && rawText != rawBaseline) || (initial != null && original == null)
    fun leave() { if (dirty) discard = true else onBack() }
    fun set(key: String, value: Any?) { if (!readOnly) fields = if (value == null) fields - key else fields + (key to value) }
    fun save() = actions.launch("已保存，后续任务生效") {
        if (raw) { val parsed = repository.parseAgent(rawText); name = parsed.name; fields = parsed.fields; prompt = parsed.systemPrompt }
        require(name.isNotBlank()) { "请填写 Agent 标识" }
        repository.saveAgent(scope, name, fields, prompt, original)
        baseline = Triple(name, fields, prompt)
        onBack()
    }
    AgentManagementBack(registerBack) {
        when { full != null -> { if (readOnly) full = null else editorBack?.invoke(); true }
            target != null -> { target = null; true }
            thinking -> { thinking = false; true }
            discard -> { discard = false; true }
            else -> { leave(); true } }
    }
    ManagementPage(if (original == null) "新建 Agent" else name, { leave() }, actions = {
        TextButton(onClick = { actions.launch {
            if (!raw) { rawText = if (readOnly && original != null) original.content else repository.renderAgent(name, fields, prompt); rawBaseline = rawText }
            else if (!readOnly) { val parsed = repository.parseAgent(rawText); name = parsed.name; fields = parsed.fields; prompt = parsed.systemPrompt }
            raw = !raw
        } }) { Text(if (raw) "结构化" else "原始定义") }
    }, footer = { if (!readOnly) ManagementSaveBar(dirty, actions.busy, { save() }, {
        if (original == null && initial != null) onBack()
        else { name = baseline.first; fields = baseline.second; prompt = baseline.third; scope = baselineScope; raw = false }
    }, actions.error, canSave = name.isNotBlank() && fields["description"]?.toString()?.isNotBlank() == true) }) {
        if (readOnly) ManagementBanner("${managementSourceLabel(original!!.source)} 定义只读。返回详情复制到项目或用户后修改。", "lock")
        if (raw) {
            ManagementField("", rawText, { rawText = it }, mono = true, multiline = true, readOnly = readOnly)
        } else {
            ManagementGroup("基本信息") {
                ManagementField("标识", name, { name = it }, mono = true, readOnly = readOnly || original != null)
                ManagementField("用途", fields["description"]?.toString().orEmpty(), { set("description", it) }, readOnly = readOnly)
                if (original == null) ManagementSegments(listOf("project" to "项目", "user" to "用户"), if (scope == ConfigurationScope.PROJECT) "project" else "user", { scope = if (it == "project") ConfigurationScope.PROJECT else ConfigurationScope.GLOBAL; onScopeChange(scope) }, { it != "project" || state.context.projectPath != null })
                ManagementHint(original?.path ?: if (scope == ConfigurationScope.PROJECT) ".omp/agents/$name.md" else "~/.omp/agent/agents/$name.md", "save")
                if (original == null && state.agents.any { it.name == name }) ManagementBanner("存在同名定义，保存会整份遮蔽它。", "layers", warning = true)
            }
            ManagementGroup("系统提示词", action = { TextButton(onClick = { full = "prompt" }) { Text("全屏") } }) {
                ManagementSegments(listOf("edit" to "编辑", "preview" to "预览"), if (preview) "preview" else "edit", { preview = it == "preview" })
                if (preview) Markdown(prompt) else ManagementField("Markdown", prompt, { if (!readOnly) prompt = it }, multiline = true, readOnly = readOnly)
            }
            ManagementGroup("模型") {
                ManagementCandidates(configurationStrings(fields["model"]), state, { set("model", it) }, readOnly = readOnly)
                Box {
                ManagementRow("思考强度", managementThinkingLabel(fields["thinkingLevel"] as? String), "neurology",
                    if (readOnly) null else { { thinking = true } })
                    ManagementThinkingPicker(fields["thinkingLevel"] as? String, { thinking = false }, { set("thinkingLevel", it); thinking = false }, expanded = thinking)
                }
            }
            ManagementGroup("工具策略") {
                ManagementSegments(listOf("default" to "默认工具", "list" to "指定列表"), if (fields.containsKey("tools")) "list" else "default",
                    { set("tools", if (it == "default") null else configurationStrings(fields["tools"])) }, { !readOnly })
                AnimatedVisibility(fields.containsKey("tools")) {
                    Column {
                        AgentCatalogueSelection("允许的工具", state.tools, configurationStrings(fields["tools"]), !readOnly) { set("tools", it) }
                        if (configurationStrings(fields["tools"]).isEmpty()) ManagementBanner("显式空列表：不提供默认工具。", "block", warning = true)
                    }
                }
                ManagementHint("工具列表不是完整沙箱，MCP 与扩展工具可能仍然可用。")
            }
            ManagementGroup("下级派发") {
                val spawns = fields["spawns"]
                val mode = when { !fields.containsKey("spawns") -> "default"; spawns == "*" -> "all"; choosingSpawns || configurationStrings(spawns).isNotEmpty() -> "list"; else -> "none" }
                ManagementSegments(listOf("default" to "默认", "all" to "所有", "list" to "指定", "none" to "禁止"), mode,
                    { choosingSpawns = it == "list"; set("spawns", when (it) { "default" -> null; "all" -> "*"; else -> emptyList<String>() }) }, { !readOnly })
                if (mode == "list") AgentCatalogueSelection("允许派发", state.agents.filter { it.name != name }.map { ConfigurationCapability(it.name, it.description, it.source) },
                    configurationStrings(spawns), !readOnly) { set("spawns", it) }
                if (fields.containsKey("tools") && "task" !in configurationStrings(fields["tools"])) ManagementHint("未选择 task 工具，派发配置可能不会生效。", "link_off")
                ManagementHint("最大递归深度：${configurationDisplay(configurationValue(state.effectiveValues, "task.maxDepth"))}")
            }
            AgentCatalogueSelection("自动加载技能", state.skills, configurationStrings(fields["autoloadSkills"]), !readOnly) { set("autoloadSkills", it) }
            ManagementGroup("输出") {
                AgentOptionalBoolean("结构化结果", "structured", fields, readOnly, ::set)
                ManagementRow("输出 Schema", configurationDisplay(fields["output"]), "output", if (readOnly) null else { { full = "output" } })
            }
            ManagementGroup("执行") {
                AgentOptionalBoolean("阻塞等待结果", "blocking", fields, readOnly, ::set)
                AgentOptionalBoolean("读取时摘要", "readSummarize", fields, readOnly, ::set)
            }
            listOf("prewalk" to "Prewalk", "advisor" to "顾问").forEach { (id, title) ->
                ManagementGroup(title) {
                    val value = fields[id]
                    val mode = when (value) { null -> "inherit"; false -> "off"; true -> "on"; else -> "target" }
                    ManagementSegments(listOf("inherit" to "默认", "off" to "关闭", "on" to "开启", "target" to "指定"), mode,
                        { when (it) { "inherit" -> set(id, null); "off" -> set(id, false); "on" -> set(id, true); else -> target = id } }, { !readOnly })
                    if (mode == "target") ManagementRow("目标", value.toString(), "swap_horiz", if (readOnly) null else { { target = id } })
                    if (id == "prewalk") ManagementHint("首次编辑或写入满足条件后切换执行模型，不是起始模型。")
                }
            }
            if (fields.keys.any { it !in agentKnownFields }) ManagementGroup("未识别字段") {
                fields.filterKeys { it !in agentKnownFields }.forEach { (key, value) -> ManagementRow(key, configurationDisplay(value), "data_object") }
            }
        }
    }
    target?.let { id -> ManagementModelPicker(state, fields[id] as? String, onDismiss = { target = null }, onPick = { set(id, it); target = null }) }
    full?.let { which ->
        if (which == "prompt") AgentSheet("系统提示词", { full = null }) {
            ManagementField("", prompt, { if (!readOnly) prompt = it }, multiline = true, readOnly = readOnly)
        } else {
        val value = agentJson(fields["output"] ?: emptyMap<String, Any?>())
        if (readOnly) CodeDetailScreen("输出结构", value, "json") { full = null }
        else ManagementEditableCodeScreen("输出结构", value, "json", { full = null }, { editorBack = it }, error = actions.error, saving = actions.busy) { text ->
            actions.launch {
                set("output", agentParseJson(text))
                full = null
            }
        }
        }
    }
    if (discard) AgentDiscardDialog({ discard = false }, { discard = false; onBack() })
}

private val agentKnownFields = setOf("name", "description", "model", "thinkingLevel", "tools", "spawns", "autoloadSkills", "output", "structured", "blocking", "readSummarize", "prewalk", "advisor")

@Composable
private fun AgentOptionalBoolean(title: String, key: String, fields: Map<String, Any?>, readOnly: Boolean, set: (String, Any?) -> Unit) {
    Text(title, style = MaterialTheme.typography.titleSmall)
    ManagementSegments(listOf("inherit" to "继承默认", "on" to "开启", "off" to "关闭"),
        when (fields[key]) { true -> "on"; false -> "off"; else -> "inherit" },
        { set(key, when (it) { "on" -> true; "off" -> false; else -> null }) }, { !readOnly })
}

@Composable
internal fun AgentDiscardDialog(onCancel: () -> Unit, onDiscard: () -> Unit) {
    AlertDialog(onDismissRequest = onCancel, title = { Text("舍弃未保存的修改？") },
        confirmButton = { TextButton(onClick = onDiscard) { Text("舍弃") } }, dismissButton = { TextButton(onClick = onCancel) { Text("继续编辑") } })
}

private val agentEditorJson = Json { prettyPrint = true }
internal fun agentJson(value: Any?): String = agentEditorJson.encodeToString(JsonElement.serializer(), configurationJson(value))
internal fun agentParseJson(text: String): Any? = configurationFromJson(Json.parseToJsonElement(text))

@Composable
private fun AgentGeneration(repository: AgentManagementRepository, state: AgentManagementState, defaultScope: ConfigurationScope,
    onScopeChange: (ConfigurationScope) -> Unit, onBack: () -> Unit, registerBack: ((() -> Boolean)?) -> Unit, onEdit: (ManagedAgent) -> Unit) {
    val actions = LocalManagementActions.current
    val coroutineScope = rememberCoroutineScope()
    var description by remember { mutableStateOf("") }
    var result by remember { mutableStateOf<ManagedAgent?>(null) }
    var stage by remember { mutableStateOf("description") }
    var scope by remember { mutableStateOf(defaultScope) }
    var job by remember { mutableStateOf<Job?>(null) }
    var generating by remember { mutableStateOf(false) }
    var error by remember { mutableStateOf<String?>(null) }
    var discard by remember { mutableStateOf(false) }
    fun generate() {
        if (description.isBlank()) { error = "请先描述需求"; return }
        job = coroutineScope.launch {
            generating = true; error = null
            try { val content = repository.generateAgent(description); result = repository.parseAgent(content); stage = "preview" }
            catch (failure: kotlinx.coroutines.CancellationException) { throw failure }
            catch (failure: Throwable) { error = failure.message ?: failure.toString() }
            finally { generating = false }
        }
    }
    fun back() {
        when { generating -> job?.cancel(); stage == "save" -> stage = "preview"
            description.isNotBlank() || result != null -> discard = true; else -> onBack() }
    }
    AgentManagementBack(registerBack) { if (discard) discard = false else back(); true }
    DisposableEffect(Unit) { onDispose { job?.cancel() } }
    ManagementPage("AI 生成 Agent", { back() }) {
        ManagementStepper(listOf("description" to "描述", "preview" to "预览", "save" to "保存"), stage)
        if (stage == "description" || generating) {
        ManagementField("想要一个什么样的 Agent", description, { description = it }, multiline = true, readOnly = generating)
        ManagementHint("使用当前默认角色发起真实模型请求，可能产生费用。", "payments")
        }
        error?.let { ManagementBanner(it, error = true) }
        if (generating) { LinearProgressIndicator(Modifier.fillMaxWidth()); TextButton(onClick = { job?.cancel() }) { Text("取消生成") } }
        else if (stage == "description") Button(onClick = { generate() }) { Text(if (error == null) "生成" else "重新生成") }
        else result?.let { definition ->
            if (stage == "preview") {
                HighlightedCode(definition.content, "markdown")
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    TextButton(onClick = { generate() }) { Text("重新生成") }
                    TextButton(onClick = { onEdit(definition) }) { Text("手工修改") }
                    Button(onClick = { stage = "save" }) { Text("下一步") }
                }
            } else {
                SettingsLabel("保存到")
                listOf(ConfigurationScope.PROJECT to "项目", ConfigurationScope.GLOBAL to "用户").forEachIndexed { index, (destination, label) ->
                    ManagementRow(label, if (destination == ConfigurationScope.PROJECT) ".omp/agents/${definition.name}.md" else "~/.omp/agent/agents/${definition.name}.md", "", { scope = destination; onScopeChange(destination) }, index, 2,
                        enabled = destination != ConfigurationScope.PROJECT || state.context.projectPath != null, trailing = { RadioButton(scope == destination, null, enabled = destination != ConfigurationScope.PROJECT || state.context.projectPath != null) })
                }
                Button(onClick = { actions.launch { repository.saveAgent(scope, definition.name, definition.fields, definition.systemPrompt); onBack() } }, enabled = !actions.busy) { Text("保存") }
                TextButton(onClick = { stage = "preview" }) { Text("上一步") }
            }
        }
    }
    if (discard) AgentDiscardDialog({ discard = false }, { discard = false; onBack() })
}

@Composable
private fun AgentOverrides(repository: AgentManagementRepository, state: AgentManagementState, agent: ManagedAgent,
    scope: ConfigurationScope, onScopeChange: (ConfigurationScope) -> Unit, onBack: () -> Unit,
    registerBack: ((() -> Boolean)?) -> Unit) {
    val actions = LocalManagementActions.current
    val definitions = listOf(
        "task.agentModelOverrides" to "模型",
        "task.agentPrewalk" to "Prewalk",
        "task.agentAdvisor" to "顾问",
        "task.agentSoftRequestBudget" to "模型请求次数软上限",
        "task.agentServiceTierOverrides" to "服务等级",
        "task.agentCompactionThresholdOverrides" to "上下文压缩阈值",
        "task.agentAccountPools" to "专属账号池",
    )
    val source = if (scope == ConfigurationScope.PROJECT) state.projectValues else state.globalValues
    var drafts by remember(scope) { mutableStateOf(definitions.associate { (key, _) -> key to configurationMap(configurationValue(source, key))[agent.name] }) }
    var baseline by remember(scope) { mutableStateOf(drafts) }
    var discard by remember { mutableStateOf(false) }
    var target by remember { mutableStateOf<String?>(null) }
    var jsonEditor by remember { mutableStateOf(false) }
    var editorBack by remember { mutableStateOf<(() -> Unit)?>(null) }
    var pendingScope by remember { mutableStateOf<ConfigurationScope?>(null) }
    var editingOverride by remember { mutableStateOf<String?>(null) }
    var menuOverride by remember { mutableStateOf<String?>(null) }
    val dirty = drafts != baseline
    fun set(key: String, value: Any?) { drafts = drafts + (key to value) }
    fun leave() { if (dirty) discard = true else onBack() }
    AgentManagementBack(registerBack) {
        when { jsonEditor -> { editorBack?.invoke(); true }; target != null -> { target = null; true }
            editingOverride != null -> { editingOverride = null; true }; menuOverride != null -> { menuOverride = null; true }
            discard -> { discard = false; true }; else -> { leave(); true } }
    }
    ManagementPage("运行覆盖", { leave() },
        actions = { ManagementScopeChip(scope, { if (!dirty) onScopeChange(it) else { pendingScope = it; discard = true } }, state.context.projectPath != null) },
        footer = { ManagementSaveBar(dirty, actions.busy, { actions.launch("已保存运行覆盖") {
            val changes = definitions.filter { drafts[it.first] != baseline[it.first] }.associate { (key, _) ->
                val existing = configurationMap(configurationValue(source, key))
                val value = drafts[key]
                key to if (value == null) existing - agent.name else existing + (agent.name to value)
            }
            repository.updateSettings(scope, changes)
            baseline = drafts
        } }, { drafts = baseline }, actions.error) }) {
        ManagementBanner("不修改定义文件。覆盖按名称精确匹配，从后续任务开始生效。")
        definitions.forEach { (key, title) ->
            val field = when (key) { "task.agentModelOverrides" -> "model"; "task.agentPrewalk" -> "prewalk"; "task.agentAdvisor" -> "advisor"; else -> "" }
            val default = agent.fields[field]
            val inherited = configurationMap(configurationValue(state.effectiveValues, key))[agent.name]
            ManagementGroup(title, action = { if (drafts[key] != null) TextButton(onClick = { set(key, null) }) { Text("清除覆盖") } }) {
                ManagementLayers(listOf(ManagementLayer("定义默认", if (field.isBlank()) "沿用全局" else configurationDisplay(default), "description")))
                Box {
                    ManagementRow("覆盖", drafts[key]?.let(::configurationDisplay) ?: "未设置", "edit", {
                        if (key in listOf("task.agentPrewalk", "task.agentAdvisor", "task.agentServiceTierOverrides")) menuOverride = key else editingOverride = key
                    })
                    ManagementMenu(menuOverride == key, { menuOverride = null }) {
                        if (key == "task.agentServiceTierOverrides") {
                            listOf("default" to "标准", "priority" to "优先", "flex" to "弹性", "auto" to "自动", "scale" to "Scale", "ultrafast" to "Ultrafast").forEach { (value, label) ->
                                ManagementMenuItem(text = { Text(label) }, selected = drafts[key] == value, leadingIcon = { Symbol("speed") }, onClick = { set(key, value); menuOverride = null })
                            }
                        } else {
                            listOf("inherit" to "沿用定义", "default" to "沿用全局", "off" to "关闭", "on" to "开启默认目标", "target" to "指定目标").forEach { (value, label) ->
                                ManagementMenuItem(text = { Text(label) }, selected = drafts[key] == value || value == "inherit" && drafts[key] == null, leadingIcon = { Symbol(if (value == "off") "block" else "link") }, onClick = { menuOverride = null; if (value == "target") target = key else set(key, if (value == "inherit") null else value) })
                            }
                        }
                    }
                }
                ManagementLayers(listOf(ManagementLayer("有效", configurationDisplay(drafts[key] ?: inherited ?: default), "done_all", selected = true)))
            }
        }
    }
    editingOverride?.let { key ->
        AgentSheet(definitions.first { it.first == key }.second, { editingOverride = null }) {
            Column(Modifier.heightIn(max = 600.dp).verticalScroll(rememberScrollState())) {
                when (key) {
                    "task.agentModelOverrides" -> ManagementCandidates(configurationStrings(drafts[key] ?: agent.fields["model"]), state, { set(key, it) })
                    "task.agentSoftRequestBudget" -> {
                        val text = drafts[key]?.toString().orEmpty()
                        ManagementField("请求次数软上限 · 次请求", text, { value -> set(key, value.takeIf(String::isNotBlank)?.let { it.toIntOrNull() ?: it }) })
                        ManagementHint("统计模型请求次数，不是费用金额")
                        if (text.isNotBlank() && (text.toIntOrNull() == null || (text.toIntOrNull() ?: -1) < 0)) ManagementHint("请输入非负整数", error = true)
                    }
                    "task.agentCompactionThresholdOverrides" -> {
                        ManagementField("上下文压缩阈值", drafts[key]?.toString().orEmpty(), { value -> set(key, value.ifBlank { null }?.let { it.toIntOrNull() ?: it }) })
                        ManagementHint("支持 token 数或百分比")
                    }
                    "task.agentAccountPools" -> {
                        val pools = configurationMap(drafts[key])
                        (state.accounts.map { it.provider } + pools.keys).distinct().forEach { provider ->
                            val accounts = state.accounts.filter { it.provider == provider }
                            val selected = configurationStrings(pools[provider])
                            ManagementGroup(provider, action = { if (provider in pools) TextButton({ set(key, (pools - provider).ifEmpty { null }) }) { Text("不限制") } }) {
                                (accounts.map { it.id } + selected).distinct().forEach { id ->
                                    val account = accounts.firstOrNull { it.id == id }
                                    ManagementRow(account?.label ?: id, account?.status ?: "未发现的已配置账号", "account_circle", trailing = {
                                        Switch(!pools.containsKey(provider) || id in selected, { checked ->
                                            val starting = if (pools.containsKey(provider)) selected else accounts.map { it.id }
                                            set(key, pools + (provider to if (checked) (starting + id).distinct() else starting - id))
                                        })
                                    })
                                }
                            }
                        }
                        TextButton({ jsonEditor = true }) { Text("完整账号池 JSON") }
                        if (pools.values.any { configurationStrings(it).isEmpty() }) ManagementBanner("显式空池不允许使用账号，也不会退回 API Key。", "block", warning = true)
                    }
                }
                Button({ editingOverride = null }, modifier = Modifier.fillMaxWidth().padding(top = 16.dp)) { Text("完成") }
            }
        }
    }
    target?.let { key -> ManagementModelPicker(state, drafts[key] as? String, onDismiss = { target = null }, onPick = { set(key, it); target = null }) }
    if (jsonEditor) ManagementEditableCodeScreen("专属账号池", agentJson(drafts["task.agentAccountPools"] ?: emptyMap<String, Any?>()), "json", { jsonEditor = false }, { editorBack = it }, error = actions.error, saving = actions.busy) { text ->
        actions.launch { val value = agentParseJson(text); require(value is Map<*, *>) { "账号池必须为 JSON 对象" }; set("task.agentAccountPools", value); jsonEditor = false }
    }
    if (discard) AgentDiscardDialog({ discard = false; pendingScope = null }, {
        discard = false
        val next = pendingScope
        pendingScope = null
        if (next != null) onScopeChange(next) else onBack()
    })
}
